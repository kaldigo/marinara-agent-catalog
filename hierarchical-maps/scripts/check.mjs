import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const engine=process.env.MARINARA_ENGINE_ROOT;
const tools=engine?createRequire(path.join(path.resolve(engine),'package.json')):require;
const {sharedTreeShakingPlugin}=await import('./esbuild-host-plugins.mjs');
const shared=path.join(root,'src/shared/index.js');
const runtime=path.join(root,'src/engine/packages/maps-shared/src/runtime-prompt.ts');
const model=path.join(root,'src/engine/packages/maps-shared/src/maps-model.ts');
const effects=path.join(root,'src/engine/packages/maps-shared/src/location-effects.ts');
const worldLocation=path.join(root,'src/engine/packages/maps-shared/src/world-state-location.ts');
const result=await tools('esbuild').build({stdin:{contents:`export * from ${JSON.stringify(runtime)}; export * from ${JSON.stringify(model)}; export * from ${JSON.stringify(effects)}; export * from ${JSON.stringify(worldLocation)};`,resolveDir:root,loader:'ts'},bundle:true,write:false,format:'cjs',platform:'node',alias:{'@marinara-engine/shared':shared},nodePaths:engine?['packages/server/node_modules','packages/client/node_modules','packages/shared/node_modules','node_modules'].map(p=>path.join(path.resolve(engine),p)):[path.join(root,'node_modules')],plugins:[sharedTreeShakingPlugin({roots:[path.dirname(shared)]})]});
const module={exports:{}};
new Function('module','exports','require',result.outputFiles[0].text)(module,module.exports,require);
const api=module.exports;
assert.equal(api.formatWorldStateLocation([{name:'Home'},{name:'Upstairs'},{name:'Bedroom'}]),'Home, Upstairs, Bedroom');
let count=0;
for(const mode of ['roleplay','game']) {
 const templates=api.defaultSpatialTurnPromptTemplates();
 assert(templates[mode].includes('${knownLocationsBlock}'));
 const hidden={...templates,[mode]:templates[mode].replace('${knownLocationsBlock}','')};
 assert(api.spatialTurnPromptTemplatesSchema.safeParse(hidden).success,'Known-location variable is optional');
 assert(!api.spatialTurnPromptTemplatesSchema.safeParse({...templates,[mode]:templates[mode].replace('${authorityInstruction}','')}).success,'Authority remains required');
 const projection={kind:'owner',chatId:'fixture',ownerMode:mode,currentLocationId:'kitchen',definitionRevision:1,breadcrumb:[{id:'home',name:'Home'},{id:'kitchen',name:'Kitchen'}],description:'A familiar kitchen.',modelMemory:null,destinations:[{id:'hall',name:'Hall'}],knownLocations:[{id:'kitchen',path:'Home > Kitchen'},{id:'away',path:'Away from home'}],lorebookEntryIds:['kitchen-lore'],omittedDestinationCount:0};
 const before=JSON.stringify(projection);
 const shown=api.formatOwnerSpatialPrompt(projection,templates[mode]);
 const omitted=api.formatOwnerSpatialPrompt(projection,hidden[mode]);
 assert(shown.includes('Known map locations'));
 assert(shown.includes('Away from home'));
 assert(!omitted.includes('Known map locations'));
 assert(!omitted.includes('Away from home'));
 assert(omitted.includes('Hall [hall]'),'Nearby destinations remain');
 assert(omitted.includes('Current location ID: kitchen'));
 assert(omitted.includes('Treat this as the authoritative'));
 assert(omitted.includes('[spatial_move:'),'Native movement instructions remain');
 assert.equal(JSON.stringify(projection),before,'Prompt formatting must not mutate map or linked lore');
 const existing={...projection,turnPromptTemplate:hidden[mode]};
 assert.equal(api.formatOwnerSpatialPrompt(existing),omitted,'Saved templates are used without explicit override');
 const normalized=api.normalizeSpatialTurnPromptTemplates(hidden);
 assert.equal(normalized[mode],hidden[mode].trim(),'Existing saved templates without the list survive normalization');
 count+=14;
}
const manifest=JSON.parse(await fs.readFile(path.join(root,'manifest.json'),'utf8'));
const source=JSON.parse(await fs.readFile(path.join(root,'marinara-source.json'),'utf8'));
assert.equal(manifest.id,'hierarchical-maps');
assert.equal(manifest.version,JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8')).version);
assert.equal(source.includeInMain,true);
assert.equal(source.package.name,'World Maps');
assert.equal(manifest.name,'World Maps');
for(const file of Object.values(manifest.entrypoints)) await fs.access(path.join(root,'dist/package',file));
console.log(`Passed ${count} Roleplay/Game prompt checks, package identity and prepared-entrypoint checks.`);
const original={background:'manual.jpg',other:{keep:true},entryStateOverrides:{disabled:{enabled:false,ephemeral:8},counter:{ephemeral:17},enabled:{enabled:true}}};
const snapshot=JSON.stringify(original);
let state=api.applyLocationEffects(original,['counter','enabled','disabled'],'/kitchen.png','kitchen');
assert.equal(state.entryStateOverrides.counter.enabled,false);
assert.equal(state.entryStateOverrides.counter.ephemeral,17);
assert.equal(state.background,'/kitchen.png');
state=api.applyLocationEffects(state,['enabled'],'/hall.png','hall');
assert.deepEqual(state.entryStateOverrides.counter,{ephemeral:17});
assert.deepEqual(state.entryStateOverrides.disabled,{enabled:false,ephemeral:8});
state=api.applyLocationEffects(state,[],null,null);
assert.deepEqual(state.entryStateOverrides,original.entryStateOverrides);
assert.equal(state.background,'manual.jpg');
assert.deepEqual(state.other,original.other);
assert.equal(JSON.stringify(original),snapshot,'Effect calculation is immutable');
let manual=api.applyLocationEffects(original,['counter'],'/kitchen.png','kitchen');
manual={...manual,background:'chosen.jpg',entryStateOverrides:{...manual.entryStateOverrides,counter:{enabled:true,ephemeral:15}}};
const released=api.applyLocationEffects(manual,[],null,null);
assert.equal(released.background,'chosen.jpg','Do not overwrite a manual background change');
assert.deepEqual(released.entryStateOverrides.counter,{enabled:true,ephemeral:15},'Do not restore stale flags/counters over another edit');
assert.equal(api.applyLocationEffects(manual,['counter'],undefined,'kitchen').background,'chosen.jpg','Transient image lookup failure preserves background');
console.log('Passed location-effect restoration, overlapping exclusions, manual edits, counters, image-failure and immutability checks.');
